@st.cache_data(show_spinner="جارٍ توليد توزيعات المحاكاة…")
def _gap_samples(reps: int = 3000) -> dict:
    """توزيع إحصاء ARCH-LM الفعلي عند أحجام عيّنة مختلفة (تحت الفرضية الصفرية)."""
    from core.engine import simulate_dgp, design_from, compute_stat
    rng = np.random.default_rng(404)
    out = {}
    for n in [25, 40, 60, 100, 200, 500]:
        v = np.empty(reps)
        for i in range(reps):
            d = simulate_dgp(n, 0.6, 1.0, 0.0, "normal", 0.0, rng)
            y, X = design_from(d["y"], d["x"])
            v[i] = compute_stat("arch", y, X, q=2)
        out[n] = v
    return out


samples = _gap_samples()
plotly(anim_asymptotic_gap([25, 40, 60, 100, 200, 500], samples, df=2),
       key="why_gap")

ns = [25, 40, 60, 100, 200, 500]
cv = sps.chi2.ppf(0.95, 2)
rates = [float((samples[n] > cv).mean()) for n in ns]

